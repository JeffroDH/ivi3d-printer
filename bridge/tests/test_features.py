class Hook(BaseHTTPRequestHandler):
    got = []
    def log_message(self, *a): pass
    def do_POST(self):
        n = int(self.headers["Content-Length"]); Hook.got.append((self.path, self.headers.get("Title"), self.rfile.read(n).decode()))
