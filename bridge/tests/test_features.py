class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(); t = self.tmp
        self.cfg = dict(B.DEFAULT_CONFIG, api_key="KEY", spool_dir=os.path.join(t, "jobs"), listen_port=0, notify=False,
                        history_file=os.path.join(t, "h.json"), macros_file=os.path.join(t, "m.json"),
                        backup_dir=os.path.join(t, "backups"), timelapse_dir=os.path.join(t, "tl"))
        os.makedirs(self.cfg["spool_dir"])
        self.ms = MonitorSerial(); self.ser = FakeSerial(); self.port = self.ms
        self.bridge = B.Bridge(self.cfg, serial_factory=lambda: self.port, awake_factory=lambda: None)
        self.srv = B.serve(self.cfg, self.bridge, start_monitor=False)
        threading.Thread(target=self.srv.serve_forever, daemon=True).start()
        self.url = f"http://127.0.0.1:{self.srv.server_port}"; self.bridge.monitor.poll_once()
    def tearDown(self): self.srv.shutdown()
    def get(self, path, key="KEY", raw=False):
        with urllib.request.urlopen(urllib.request.Request(self.url + path, headers={"X-Api-Key": key}), timeout=5) as r:
            return (r.headers["Content-Type"], r.read()) if raw else json.loads(r.read())
    def post(self, path, obj, key="KEY"):
        r = urllib.request.Request(self.url + path, data=json.dumps(obj).encode(), headers={"X-Api-Key": key, "Content-Type": "application/json"})
        with urllib.request.urlopen(r, timeout=10) as resp: return json.loads(resp.read())
    def err(self, fn, *a, **k):
        with self.assertRaises(urllib.error.HTTPError) as e: fn(*a, **k)
        return e.exception.code
    def stream(self, n=100000):
        self.port = self.ser; self.cfg["mode"] = "serial"
        p = os.path.join(self.cfg["spool_dir"], "long.gcode"); open(p, "w").write("\n".join("G1 X%d" % (i % 100) for i in range(n)))
        self.bridge.submit(p, "long.gcode", start=True)
        while self.bridge.job.state != "Printing": time.sleep(0.01)

