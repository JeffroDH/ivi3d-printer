"""End-to-end tests: ivibridge (ARM build under qemu-arm, or native with IVIBRIDGE_BIN) between a fake
STM32 (pty) and a fake touchscreen app (opens the link path the daemon creates), plus the HTTP API."""
import json, os, re, shutil, signal, socket, subprocess, sys, tempfile, time, unittest, urllib.request, urllib.error
sys.path.insert(0, os.path.dirname(__file__))
from sim_stm32 import FakeSTM32, FakeApp

BIN = os.environ.get("IVIBRIDGE_BIN", os.path.join(os.path.dirname(__file__), "..", "bin", "ivibridge-armv7-static"))
RUNNER = [] if os.environ.get("IVIBRIDGE_NATIVE") else ["qemu-arm"]
KEY = "test-key-123"

def free_port():
    s = socket.socket(); s.bind(("127.0.0.1", 0)); p = s.getsockname()[1]; s.close(); return p

def gcode(n, extra=()):
    out = [";Generated by IVI 3licer", ";header_type: 3dp", "G90", "M82"]
    for i in range(n):
        if i % 50 == 0: out.append("M73 P%d R%d ; progress" % (i * 100 // n, (n - i) // 10))
        out.append("G1 X%.2f Y%.2f E%.4f F1800 ; move %d" % (i % 40, (i * 7) % 40, i * 0.01, i))
        if i % 17 == 0: out.append("")
    out += list(extra)
    return "\n".join(out) + "\n"

class Base(unittest.TestCase):
    plain_ok_nook = False; bad_at = None; ok_delay = 0.002; key = KEY; poll = "0"; sim_kw = {}; extra_args = []
    def setUp(self):
        self.d = tempfile.mkdtemp(prefix="ivib-")
        self.up = os.path.join(self.d, "WifiFile"); os.mkdir(self.up)
        self.sim = FakeSTM32(plain_ok_nook=self.plain_ok_nook, ok_delay=self.ok_delay, bad_checksum_at=self.bad_at, **self.sim_kw)
        self.real = os.path.join(self.d, "ivi-stm32"); os.symlink(self.sim.slave_name, self.real)
        self.link = os.path.join(self.d, "ttyUSB0")
        self.port = free_port(); self.log = os.path.join(self.d, "ivibridge.log")
        args = RUNNER + [BIN, "-s", self.real, "-L", self.link, "-p", str(self.port), "-b", "127.0.0.1", "-u", self.up,
                         "-l", self.log, "-n", "-P", self.poll]
        if self.key: args += ["-k", self.key]
        args += list(self.extra_args)
        self.env = os.environ.copy(); self.env["IVIB_DIR"] = self.d
        self.env["IVIB_WWW"] = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "www")
        if getattr(self, "log_max", None): self.env["IVIB_LOG_MAX"] = str(self.log_max)
        self.proc = subprocess.Popen(args, env=self.env)
        end = time.time() + 15
        while time.time() < end and not os.path.islink(self.link): time.sleep(0.05)
        self.assertTrue(os.path.islink(self.link), "daemon did not create the app link")
        self.wait_http()
        self.app = FakeApp(self.link)

    def tearDown(self):
        self.app.close()
        if self.proc.poll() is None:
            self.proc.send_signal(signal.SIGTERM)
            try: self.proc.wait(10)
            except subprocess.TimeoutExpired: self.proc.kill()
        self.sim.close()
        if os.environ.get("KEEP_LOGS"):
            shutil.copy(self.log, os.environ["KEEP_LOGS"] + "/" + self.id().split(".")[-1] + ".log")
        shutil.rmtree(self.d, ignore_errors=True)

    def wait_http(self):
        end = time.time() + 15
        while time.time() < end:
            try: socket.create_connection(("127.0.0.1", self.port), 0.5).close(); return
            except OSError: time.sleep(0.1)
        self.fail("http not up")

    def http(self, method, path, body=None, key=KEY, ctype="application/json", raw=None):
        url = "http://127.0.0.1:%d%s" % (self.port, path)
        data = raw if raw is not None else (json.dumps(body).encode() if body is not None else None)
        req = urllib.request.Request(url, data=data, method=method)
        if key: req.add_header("X-Api-Key", key)
        if data is not None: req.add_header("Content-Type", ctype)
        try:
            with urllib.request.urlopen(req, timeout=10) as r:
                t = r.read(); return r.status, (json.loads(t) if t and r.headers.get("Content-Type", "").startswith("application/json") else t)
        except urllib.error.HTTPError as e:
            t = e.read(); return e.code, (json.loads(t) if t else None)

    def upload(self, name, text, start=True, key=KEY):
        b = "----ivitest"
        body = ("--%s\r\nContent-Disposition: form-data; name=\"file\"; filename=\"%s\"\r\nContent-Type: application/octet-stream\r\n\r\n" % (b, name)).encode()
        body += text.encode() + ("\r\n--%s\r\nContent-Disposition: form-data; name=\"print\"\r\n\r\n%s\r\n--%s--\r\n" % (b, "true" if start else "false", b)).encode()
        return self.http("POST", "/api/files/local", raw=body, ctype="multipart/form-data; boundary=" + b, key=key)

    def wait_state(self, pred, timeout=60):
        end = time.time() + timeout; j = None
        while time.time() < end:
            _, j = self.http("GET", "/api/job")
            if pred(j): return j
            time.sleep(0.2)
        self.fail("timeout; last /api/job = %r" % (j,))

    def numbered(self):
        out = []
        for c in self.sim.cmds():
            m = re.match(r"^N(\d+) (.*)\*\d+$", c)
            if m: out.append((int(m.group(1)), m.group(2)))
        return out

