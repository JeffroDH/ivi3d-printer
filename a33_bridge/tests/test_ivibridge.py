        i_start, i_fin = cm.index("M2411 S2"), cm.index("M2411 S4")
        self.assertLess(cm.index("M2007"), i_start); self.assertLess(i_start, i_fin)
        time.sleep(0.5)
        self.assertEqual(self.app.oks, held_before + 1 + 1)    # M105 reply + 1 deferred ack for the held jog
        self.assertEqual(self.sim.violations, [])

