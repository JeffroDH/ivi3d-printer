class T25_PersistJobsAndLogs(Base):
    """Once p1.ready appears: new uploads go to p1, idle RAM jobs migrate
    (copy + size/sha256 + delete), an in-progress job stays put until it ends,
    and the daemon log is seeded then appended on p1 (RAM copy kept)."""
    ok_delay = 0.002
    log_max = 800
    def _ready_p1(self):
        self.p1 = os.path.join(self.d, "p1")
        os.makedirs(os.path.join(self.p1, "ivibridge_jobs"), exist_ok=True)
        os.makedirs(os.path.join(self.p1, "ivibridge_logs"), exist_ok=True)
        open(os.path.join(self.d, "p1.ready"), "w").write(self.p1 + "\n")

    def test_new_upload_and_idle_migrate_and_log_persist(self):
        # land a file in RAM before p1 is visible
        s, r = self.upload("early.gcode", gcode(20), start=False); self.assertEqual(s, 201, r)
        self.assertTrue(os.path.exists(os.path.join(self.up, "early.gcode")))
        early_sha = __import__("hashlib").sha256(open(os.path.join(self.up, "early.gcode"), "rb").read()).hexdigest()
        ram_log = open(self.log).read()
        self.assertIn("starting", ram_log)
        self._ready_p1()
        # wait for the 2 s refresh + migrate
        end = time.time() + 6
        dest = os.path.join(self.p1, "ivibridge_jobs", "early.gcode")
        while time.time() < end and not os.path.exists(dest): time.sleep(0.2)
        self.assertTrue(os.path.exists(dest), "idle RAM job was not migrated")
        self.assertFalse(os.path.exists(os.path.join(self.up, "early.gcode")))
        self.assertEqual(__import__("hashlib").sha256(open(dest, "rb").read()).hexdigest(), early_sha)
        # new uploads go to p1
        s, r = self.upload("later.gcode", gcode(15), start=False); self.assertEqual(s, 201, r)
        self.assertTrue(os.path.exists(os.path.join(self.p1, "ivibridge_jobs", "later.gcode")))
        self.assertFalse(os.path.exists(os.path.join(self.up, "later.gcode")))
        # listing includes both names (only p1 now)
        s, listing = self.http("GET", "/api/files"); self.assertEqual(s, 200)
        names = [f["name"] for f in listing["files"]]
        self.assertIn("early.gcode", names); self.assertIn("later.gcode", names)
        # logs: RAM still has the start line; persist has it (seeded) and later events
        self.assertIn("starting", open(self.log).read())
        plog = os.path.join(self.p1, "ivibridge_logs", "ivibridge.log")
        end = time.time() + 4
        while time.time() < end and (not os.path.exists(plog) or "p1 ready" not in open(plog).read()):
            time.sleep(0.2)
        self.assertTrue(os.path.exists(plog))
        pt = open(plog).read()
        self.assertIn("starting", pt)          # seeded early RAM log
        self.assertIn("p1 ready", pt)
        self.assertIn("upload stored", pt)
        # RAM copy is kept
        self.assertTrue(os.path.exists(self.log))

    def test_active_job_not_moved_until_end(self):
        s, r = self.upload("printme.gcode", gcode(400), start=True); self.assertEqual(s, 201, r)
        self.wait_state(lambda j: j["state"] == "Printing", 15)
        self.http("POST", "/api/job", {"command": "pause", "action": "pause"})
        self.wait_state(lambda j: j["state"] == "Paused", 10)
        src = os.path.join(self.up, "printme.gcode")
        self.assertTrue(os.path.exists(src))
        self._ready_p1()
        # while the job is still active (paused), the RAM file and path must stay valid
        time.sleep(2.5)
        self.assertTrue(os.path.exists(src), "active job was moved mid-print")
        self.assertFalse(os.path.exists(os.path.join(self.p1, "ivibridge_jobs", "printme.gcode")))
        s, job = self.http("GET", "/api/job"); self.assertEqual(job["state"], "Paused")
        # after cancel (job ends) it should migrate
        self.http("POST", "/api/job", {"command": "cancel"})
        self.wait_state(lambda j: j["ivi"]["job_state"] == "Cancelled", 30)
        end = time.time() + 6
        dest = os.path.join(self.p1, "ivibridge_jobs", "printme.gcode")
        while time.time() < end and not os.path.exists(dest): time.sleep(0.2)
        self.assertTrue(os.path.exists(dest), "finished job was not migrated")
        self.assertFalse(os.path.exists(src))

    def test_log_rotation_caps_size(self):
        # IVIB_LOG_MAX=800 (via log_max); write enough upload log lines to roll
        for i in range(25):
            s, r = self.upload("r%d.gcode" % i, gcode(5), start=False)
            self.assertEqual(s, 201, r)
        # after rotation the live log is under the cap (plus one line of slack) and a .1 exists
        # (rotation happens on the next write after the cap is crossed)
        time.sleep(0.2)
        st = os.stat(self.log)
        self.assertTrue(os.path.exists(self.log + ".1") or st.st_size <= 800 + 200,
                        "log was neither rotated nor capped (size=%d)" % st.st_size)
        if os.path.exists(self.log + ".1"):
            self.assertLessEqual(st.st_size, 800 + 400)

