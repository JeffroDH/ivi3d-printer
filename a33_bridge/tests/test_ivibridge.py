def first_index_after(cmds, i0, pred):
    for i in range(i0, len(cmds)):
        if pred(cmds[i]): return i
    return None

class T15_HardwarePauseResume(Base):
    """Firmware V1.3.2-alpha behaviour: 'Finish pause', 'Resume complete' 1 s after the resume ack, lines in between
    dropped silently, 'CMD buffer: N' after every reply and 'Homed: YES' pushes. Fix 1: nothing streams before
    'Resume complete'; fix 4: 3DP head -> no M5."""
    plain_ok_nook = True; ok_delay = 0.01
    sim_kw = dict(strict_resume=True, resume_delay=1.0, noise=True, head="info:Head 3DP,0.3mm")
    def test_waits_for_resume_complete(self):
        self.assertTrue(self.app.send("M2051"))
        s, p = self.http("GET", "/api/printer"); self.assertEqual(p["ivi"]["head"], "3DP,0.3mm")
        s, r = self.upload("hw.gcode", gcode(4000)); self.assertEqual(s, 201, r)
        self.wait_state(lambda j: j["state"] == "Printing" and j["progress"]["filepos"] > 20)
        t0 = time.time()
        self.assertEqual(self.http("POST", "/api/job", {"command": "pause", "action": "pause"})[0], 200)
        self.wait_state(lambda j: j["state"] == "Paused", 10)
        self.assertLess(time.time() - t0, 2.5)                       # completed on "Finish pause", not the 3 s fallback
        n1 = len(self.numbered()); time.sleep(0.8); self.assertEqual(len(self.numbered()), n1)
        self.assertEqual(self.http("POST", "/api/job", {"command": "pause", "action": "resume"})[0], 200)
        self.wait_state(lambda j: j["state"] == "Printing" and j["progress"]["filepos"] > n1 + 20, 20)
        rx = self.sim.received; i_res = [i for i, (_, c) in enumerate(rx) if c == "M2411 S1"][0]
        i_next = first_index_after([c for _, c in rx], i_res, lambda c: c.startswith("N"))
        self.assertIsNotNone(self.sim.resume_complete_t)
        self.assertGreaterEqual(rx[i_next][0], self.sim.resume_complete_t)   # first job line only after Resume complete
        self.assertEqual(self.sim.dropped, [])
        execd = self.sim.executed; self.assertEqual(len(execd), len(set(execd)))
        self.assertEqual(self.http("POST", "/api/job", {"command": "cancel"})[0], 200)
        j = self.wait_state(lambda j: j["ivi"]["job_state"] == "Cancelled", 30)
        self.assertEqual(j["ivi"]["stalls"], 0); self.assertEqual(j["ivi"]["resends"], 0)
        cm = self.sim.cmds(); k = cm.index("M2411 S3")
        self.assertEqual(cm[k + 1:k + 4], ["M104 S0", "M140 S0", "M107"]); self.assertNotIn("M5", cm)
        self.assertTrue(any(l == "Homed: YES" for l in self.app.lines))   # async pushes still reach the app
        time.sleep(1.0); before = self.app.oks
        for c in ("M105", "M114", "M2007"): self.assertTrue(self.app.send(c))
        time.sleep(0.5); self.assertEqual(self.app.oks, before + 3)     # no stray job-word oks leaked to the app

