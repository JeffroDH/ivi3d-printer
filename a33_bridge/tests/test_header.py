"""Offline byte-for-byte comparison of ivibridge --add-header vs ivi_bridge.prepare_gcode."""
import os, subprocess, sys, tempfile, unittest

BIN = os.environ.get("IVIBRIDGE_BIN", os.path.join(os.path.dirname(__file__), "..", "bin", "ivibridge-armv7-static"))
RUNNER = [] if os.environ.get("IVIBRIDGE_NATIVE") else ["qemu-arm"]
HERE = os.path.dirname(os.path.abspath(__file__))
BRIDGE_DIR = os.environ.get("IVI_BRIDGE_PY", os.path.normpath(os.path.join(HERE, "..", "..", "bridge")))
DATE = "2026-11-13 12:00:00"
NOZZLE = 0.3

sys.path.insert(0, BRIDGE_DIR)
import ivi_bridge as B

def orca_sample():
    return "\n".join([
        "; thumbnail begin 16x16 80",
        "; iVBORw0KGgoAAAANSUhEUgAAABAAAAAQCAYAAAAf8/9hAAAA1234567890abcd",
        "; thumbnail end",
        "; generated by OrcaSlicer 2.2.0 on 2026-01-02 at 08:15:00",
        "; filament_type = PLA,PETG",
        "; nozzle_temperature = 210",
        "; hot_plate_temp = 60",
        "; sparse_infill_speed = 80",
        "; max_z_height = 10.5",
        "; nozzle_diameter = 0.4",
        "; filament used [mm] = 1234.5, 10.5",
        "; filament used [g] = 3.67, 0.05",
        "; estimated printing time (normal mode) = 1h 2m 3s",
        "",
        "G90",
        "M82",
        "G21",
        "M73 P0 R62",
        "G1 Z0.2 F3000",
        "G1 X10 Y10 F3000",
        "G1 X20 Y10 E1.5 F1800",
        "G1 X20 Y20 E3.0",
        "G1 X10 Y20 E4.5",
        "G1 X10 Y10 E6.0",
        "G1 Z10.5 E6.1",
        "M73 P100 R0",
        "; filament used [mm] = 9999",
        "",
    ]) + "\n"

def already_sample():
    return ";Header Start\n\n;header_type: 3dp,0.3mm\n;file_total_lines: 30\n;Header End\n\nG90\nG1 X1 Y1 E0.1\n"

def plain_sample():
    return "; a random comment\n; another\nG90\nM82\nG1 X5.25 Y-3.5 E0.25 F1200\nG1 X6 Y0 E0.5\n"

class HeaderCompare(unittest.TestCase):
    def setUp(self):
        self.d = tempfile.mkdtemp(prefix="ivi-hdr-")

    def tearDown(self):
        import shutil
        shutil.rmtree(self.d, ignore_errors=True)

    def _cmp(self, name, data):
        if isinstance(data, str):
            data = data.encode()
        src = os.path.join(self.d, name)
        py = src + ".py"
        c = src + ".c"
        open(src, "wb").write(data)
        r = B.prepare_gcode(src, py, nozzle=NOZZLE, date=DATE, strip=())
        cmd = RUNNER + [BIN, "--add-header", src, c, "--nozzle", "0.3", "--date", DATE]
        p = subprocess.run(cmd, capture_output=True, text=True)
        self.assertEqual(p.returncode, 0, p.stderr)
        want_added = r["header"]
        self.assertIn("added" if want_added else "exists", p.stderr)
        pb, cb = open(py, "rb").read(), open(c, "rb").read()
        self.assertEqual(cb, pb, "C output differs from ivi_add_header/prepare_gcode for %s (py %d c %d)" % (name, len(pb), len(cb)))
        return pb, want_added

    def test_orca_file_gets_header(self):
        out, added = self._cmp("orca.gcode", orca_sample())
        self.assertTrue(added)
        self.assertTrue(out.startswith(b";Header Start"))
        self.assertIn(b";header_type: 3dp,0.4mm", out)
        self.assertIn(b";material_type: PLA", out)
        self.assertIn(b";filament_used(m): 1.25", out)
        self.assertIn(b";filament_weight(g): 3.72", out)
        self.assertIn(b"; thumbnail begin 16x16 80", out)  # moved into the header
        # original thumbnail lines were consumed (only appear in the header block, not again in the body)
        end = out.find(b";Header End")
        self.assertEqual(out[end:].count(b"; thumbnail begin"), 0)

    def test_already_headered_file_is_unchanged(self):
        raw = already_sample().encode()
        out, added = self._cmp("already.gcode", raw)
        self.assertFalse(added)
        self.assertEqual(out, raw)

    def test_plain_file_gets_header_and_keeps_body(self):
        raw = plain_sample().encode()
        out, added = self._cmp("plain.gcode", raw)
        self.assertTrue(added)
        self.assertTrue(out.startswith(b";Header Start"))
        self.assertTrue(out.endswith(raw) or raw in out)
        # leading comments were not a ';Generated' prelude, so they stay in the body
        self.assertIn(b"; a random comment", out.split(b";Header End", 1)[1])

    def test_crlf_orca_matches_python(self):
        self._cmp("orca_crlf.gcode", orca_sample().replace("\n", "\r\n"))

if __name__ == "__main__":
    unittest.main(verbosity=2)
