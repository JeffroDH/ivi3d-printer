class BridgePage(orca.pages.PagesPluginCapabilityBase):
    DEFAULTS = {"bridge_url": DEFAULT_URL, "api_key": "", "poll_seconds": 3}

    def get_name(self):
        return "IVI3D Bridge"

    def get_default_config(self):
        return dict(self.DEFAULTS)

    def _client(self):
        cfg = _load_config(self, self.DEFAULTS)
        return BridgeClient(cfg.get("bridge_url"), cfg.get("api_key"))

    def get_ui(self):
        cfg = _load_config(self, self.DEFAULTS)
        try:
            ms = max(2, int(cfg.get("poll_seconds", 3))) * 1000
        except (TypeError, ValueError):
            ms = 3000
        return PAGE.replace("__POLL_MS__", str(ms))

    def on_message(self, data):
        # Runs on the UI thread: every call uses a short (1.5 s) timeout.
        kind = (data or {}).get("type")
        if kind == "poll":
            self.post_message(dict(self._client().status(), type="status"))
        elif kind == "command":
            self.post_message(dict(self._client().command(str(data.get("action"))), type="result"))


@orca.plugin
class Ivi3dBridgePlugin(orca.base):
    def register_capabilities(self):
        # Localhost only: the default bridge address and its endpoints.
        orca.request_permissions(
            network_http=[DEFAULT_URL + p for p in ENDPOINTS],
            network_socket=["('127.0.0.1', 5001)"])
        orca.register_capability(IviHeader)
        orca.register_capability(BridgePage)
