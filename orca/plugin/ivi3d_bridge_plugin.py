"""OrcaSlicer 2.5 plugin ("Option A"): talks only to the local IVI Bridge (http://127.0.0.1:5001), never to the printer.

Capabilities
  * "IVI3D FDM Header" (Slicing Pipeline, psGCodePostProcess): prepends the IVI 3licer ';Header Start ... header_type: 3dp'
    block to the exported G-code in place (idempotent). Config: {"enabled": true, "nozzle": "0.3"}.
  * "IVI3D Bridge" (Pages tab): bridge state, temperatures, progress, errors; Pause / Resume / Cancel / Clear stuck job.
    Config: {"bridge_url": "http://127.0.0.1:5001", "api_key": "<from the bridge installer>", "poll_seconds": 3}.
"""
import datetime
import json
import re
import urllib.error
import urllib.request

import orca

DEFAULT_URL = "http://127.0.0.1:5001"
ENDPOINTS = ("/api/job", "/api/printer", "/api/version", "/api/ivi/clear")


# ------------------------------------------------------------------ header (same logic as orca/ivi_fdm_header.py)
def _parse_time(text):
    m = re.search(r";\s*estimated printing time[^=]*=\s*(.+)", text)
    if not m:
        return 0.0
    t = 0.0
    for v, u in re.findall(r"(\d+)\s*([dhms])", m.group(1)):
        t += int(v) * {"d": 86400, "h": 3600, "m": 60, "s": 1}[u]
    return t


def _cfg(text, key, default=""):
    m = re.search(r"^;\s*" + re.escape(key) + r"\s*=\s*(.+)$", text, re.M)
    return m.group(1).split(",")[0].strip().strip('"') if m else default


def build_header(text, nozzle="0.3"):
    if text.startswith(";Header Start"):
        return text
    xs, ys, zs = [], [], []
    for line in text.splitlines():
        c = line.split(";", 1)[0]
        if not re.match(r"\s*G[01]\b", c):
            continue
        for a, arr in (("X", xs), ("Y", ys)):
            m = re.search(a + r"(-?\d+\.?\d*)", c)
            if m:
                arr.append(float(m.group(1)))
        m = re.search(r"Z(-?\d+\.?\d*)", c)
        if m:
            zs.append(float(m.group(1)))
    lines = text.split("\n")
    valid = sum(1 for l in lines if l and not l.startswith(";"))
    nz = _cfg(text, "nozzle_diameter", nozzle)
    speed = _cfg(text, "sparse_infill_speed", "60")
    try:
        speed = str(round(float(speed) * 60))
    except ValueError:
        pass
    h = [";Header Start", "", f";header_type: 3dp,{nz}mm",
         ";file_total_lines: @", f";file_valid_lines: {valid}",
         f";estimated_time(s): {_parse_time(text):.0f}",
         f";material_type: {_cfg(text, 'filament_type', 'PLA')}",
         f";nozzle_temperature(°C): {_cfg(text, 'nozzle_temperature', '210')}",
         f";build_plate_temperature(°C): {_cfg(text, 'hot_plate_temp_initial_layer', _cfg(text, 'bed_temperature_initial_layer', '60'))}",
         f";work_speed(mm/minute): {speed}",
         f";max_x(mm): {max(xs, default=0)}", f";max_y(mm): {max(ys, default=0)}", f";max_z(mm): {max(zs, default=0)}",
         f";min_x(mm): {min(xs, default=0)}", f";min_y(mm): {min(ys, default=0)}", f";min_z(mm): {min(zs, default=0)}",
         "", ";Header End", "", ";G-code for 3dp engraving",
         ";Generated by IVI 3licer (compatible header added by ivi3d-printer orca/ivi_fdm_header.py)",
         ";" + datetime.datetime.now().strftime("%a %b %d %Y %H:%M:%S"), ""]
    h[3] = f";file_total_lines: {len(h) + len(lines)}"
    return "\n".join(h) + "\n" + text


def _load_config(cap, defaults):
    try:
        cfg = json.loads(cap.get_config() or "{}")
    except (ValueError, TypeError):
        cfg = {}
    out = dict(defaults)
    out.update({k: v for k, v in cfg.items() if v is not None})
    return out


class IviHeader(orca.slicing.SlicingPipelineCapabilityBase):
    DEFAULTS = {"enabled": True, "nozzle": "0.3"}

    def get_name(self):
        return "IVI3D FDM Header"

    def get_default_config(self):
        return dict(self.DEFAULTS)

    def execute(self, ctx):
        if ctx.step != orca.slicing.Step.psGCodePostProcess:
            return orca.ExecutionResult.success()
        cfg = _load_config(self, self.DEFAULTS)
        if not cfg.get("enabled", True):
            return orca.ExecutionResult.success("IVI header disabled in settings")
        try:
            with open(ctx.gcode_path, encoding="utf-8", errors="replace") as f:
                text = f.read()
            new = build_header(text, str(cfg.get("nozzle", "0.3")))
            if new != text:
                with open(ctx.gcode_path, "w", encoding="utf-8") as f:
                    f.write(new)
        except Exception as exc:  # report, don't crash the export
            return orca.ExecutionResult.failure(orca.PluginResult.RecoverableError, f"IVI header not added: {exc}")
        return orca.ExecutionResult.success("IVI header added")


# ------------------------------------------------------------------ bridge client
class BridgeClient:
    def __init__(self, url, api_key, timeout=1.5, opener=None):
        self.url = (url or DEFAULT_URL).rstrip("/")
        self.key = api_key or ""
        self.timeout = timeout
        self.opener = opener or urllib.request.urlopen

    def _req(self, path, body=None):
        data = None if body is None else json.dumps(body).encode()
        req = urllib.request.Request(self.url + path, data=data,
                                     headers={"X-Api-Key": self.key, "Content-Type": "application/json"})
        with self.opener(req, timeout=self.timeout) as r:
            return json.loads(r.read() or b"{}")

    def status(self):
        """Returns a dict for the page; never raises."""
        try:
            job = self._req("/api/job")
            prn = self._req("/api/printer")
        except urllib.error.HTTPError as e:
            msg = "API key rejected - paste the key from the IVI Bridge installer into this tab's settings" \
                if e.code == 403 else f"bridge error HTTP {e.code}"
            return {"online": False, "error": msg}
        except Exception:
            return {"online": False, "error": f"IVI Bridge is not running at {self.url}. "
                                              "Double-click 'Install IVI Bridge.command' (or start it) and try again."}
        state = job.get("state", "?")
        return {"online": True, "state": state, "alert": classify(state),
                "file": (job.get("job") or {}).get("file", {}).get("name"),
                "progress": (job.get("progress") or {}).get("completion"),
                "temps": prn.get("temperature") or {}}

    def command(self, action):
        try:
            if action == "clear":
                return {"ok": True, "message": self._req("/api/ivi/clear", {}).get("message", "cleared")}
            body = {"pause": {"command": "pause", "action": "pause"},
                    "resume": {"command": "pause", "action": "resume"},
                    "cancel": {"command": "cancel"}}[action]
            return {"ok": True, "message": "state: " + self._req("/api/job", body).get("state", "?")}
        except KeyError:
            return {"ok": False, "message": f"unknown action {action}"}
        except urllib.error.HTTPError as e:
            try:
                detail = json.loads(e.read() or b"{}").get("error", "")
            except Exception:
                detail = ""
            return {"ok": False, "message": f"bridge refused ({e.code}) {detail}".strip()}
        except Exception as e:
            return {"ok": False, "message": f"bridge not reachable: {e}"}


def classify(state):
    s = (state or "").lower()
    if "locked rotor" in s:
        return "Motor stalled (locked rotor). On the delta this usually means a sideways move at the top after homing."
    if "halted" in s or "kill" in s:
        return "Printer halted (kill). Power-cycle the printer before the next job."
    if "status 5" in s or "still paused" in s:
        return "A previous job is still paused on the printer. Use 'Clear stuck job'."
    if s.startswith("error"):
        return state
    return ""


