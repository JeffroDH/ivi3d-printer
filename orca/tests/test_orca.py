class NoAccelM73Tests(unittest.TestCase):
    """Field fix: the IVI3D firmware stalled on Orca's M204/M205/M73 lines."""
    def load(self, sub, name):
        with open(os.path.join(D, sub, name + ".json")) as f: return json.load(f)
    def test_machine(self):
        m = self.load("machine", "IVI3D 0.3 nozzle")
        self.assertEqual(m["disable_m73"], "0"); self.assertEqual(m["emit_machine_limits_to_gcode"], "0")
        self.assertNotIn("G21", m["machine_start_gcode"] + m["layer_change_gcode"] + m["before_layer_change_gcode"])
    def test_processes(self):
        for n in ("IVI3D 0.15mm Standard", "IVI3D 0.20mm Fast", "IVI3D 0.10mm High Quality"):
            p = self.load("process", n)
            keys = [k for k in p if k.endswith(("_acceleration", "_jerk"))]
            self.assertGreaterEqual(len(keys), 18)
            for k in keys: self.assertEqual(p[k], "0", (n, k))
            self.assertEqual(p["accel_to_decel_enable"], "0")
    def test_bundle_matches(self):
        with zipfile.ZipFile(os.path.join(D, "IVI3D.orca_printer")) as z:
            m = json.loads(z.read("printer/IVI3D 0.3 nozzle.json")); p = json.loads(z.read("process/IVI3D 0.15mm Standard.json"))
        self.assertEqual(m["disable_m73"], "0"); self.assertEqual(p["default_acceleration"], "0"); self.assertEqual(p["default_jerk"], "0")

class HeaderTests(unittest.TestCase):
    def test_header(self):
        out = H.build(SAMPLE); lines = out.split("\n")
        self.assertEqual(lines[0], ";Header Start"); self.assertIn(";header_type: 3dp,0.3mm", out)
        self.assertIn(";estimated_time(s): 3723", out); self.assertIn(";material_type: PLA", out)
        self.assertIn(";max_x(mm): 10.5", out); self.assertIn(";min_y(mm): -20.0", out); self.assertIn(";max_z(mm): 5.1", out)
        self.assertIn(";work_speed(mm/minute): 3600", out); self.assertIn("Generated by IVI 3licer", out)
        total = int(next(l for l in lines if l.startswith(";file_total_lines")).split(": ")[1])
        self.assertEqual(total, len(lines))
        self.assertEqual(H.build(out), out)  # idempotent
        self.assertIn(";file_valid_lines: 5", out)

class ProfileTests(unittest.TestCase):
    def test_profiles(self):
        subprocess.run([sys.executable, os.path.join(D, "build_profiles.py")], check=True, capture_output=True)
        m = json.load(open(os.path.join(D, "machine", "IVI3D 0.3 nozzle.json")))
        self.assertEqual(m["nozzle_diameter"], ["0.3"]); self.assertEqual(m["printable_height"], "220")
        self.assertEqual(m["gcode_flavor"], "marlin"); self.assertEqual(m["use_relative_e_distances"], "1")
        r = max((float(p.split("x")[0]) ** 2 + float(p.split("x")[1]) ** 2) ** .5 for p in m["printable_area"])
        self.assertAlmostEqual(r, 105, places=2)
        self.assertTrue(m["machine_start_gcode"].splitlines()[1].startswith("G53"))
        self.assertEqual(m["print_host"], "127.0.0.1:5001")
        z = zipfile.ZipFile(os.path.join(D, "IVI3D.orca_printer")); s = json.loads(z.read("bundle_structure.json"))
        for k in ("printer_config", "filament_config", "process_config"):
            for p in s[k]: json.loads(z.read(p))
        for sub in ("filament", "process"):
            for f in os.listdir(os.path.join(D, sub)):
                self.assertEqual(json.load(open(os.path.join(D, sub, f)))["compatible_printers"], [m["name"]])

if __name__ == "__main__": unittest.main()


class VariantTests(unittest.TestCase):
    def test_fast_and_hq(self):
        subprocess.run([sys.executable, os.path.join(D, "build_profiles.py")], check=True, capture_output=True)
        P = lambda n: json.load(open(os.path.join(D, "process", n + ".json")))
        f, h = P("IVI3D 0.20mm Fast"), P("IVI3D 0.10mm High Quality")
        self.assertEqual((f["layer_height"], f["outer_wall_speed"], f["sparse_infill_speed"], f["travel_speed"], f["sparse_infill_density"]),
                         ("0.2", "50", "80", "100", "15%"))
        self.assertEqual((h["layer_height"], h["outer_wall_speed"], h["sparse_infill_speed"], h["top_shell_layers"], h["sparse_infill_density"]),
                         ("0.1", "30", "50", "12", "20%"))
        for p in (f, h):
            self.assertEqual(p["initial_layer_print_height"], "0.3")
            self.assertTrue(all(float(p[k]) <= 0.33 for k in p if k.endswith("line_width")))
            self.assertGreaterEqual(float(p["top_shell_layers"]) * float(p["layer_height"]), float(p["top_shell_thickness"]) - 1e-9)
        names = zipfile.ZipFile(os.path.join(D, "IVI3D.orca_printer")).namelist()
        st = json.loads(zipfile.ZipFile(os.path.join(D, "IVI3D.orca_printer")).read("bundle_structure.json"))
        for n in ("IVI3D 0.15mm Standard", "IVI3D 0.20mm Fast", "IVI3D 0.10mm High Quality"):
            self.assertIn(f"process/{n}.json", names); self.assertIn(f"process/{n}.json", st["process_config"])
