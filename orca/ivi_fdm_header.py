#!/usr/bin/env python3
"""Orca / Anycubic Next post-processing hook: prepend the IVI 3licer FDM header (';Header Start ... ;Header End')
to a G-code file IN PLACE, so the IVI touch screen shows type, material, time and bounds like for IVI 3licer files.

The touch-screen app (firmware.bin) parses ';header_type:', ';material_type:', ';estimated_time(s):', ';max_x/y', ';min_x/y'
and the string 'Generated by IVI 3licer'. Whether the header is REQUIRED to print is unverified - USB streaming works without it.

Orca: Process > Others > Post-processing scripts:  /usr/bin/python3 "/path/to/orca/ivi_fdm_header.py";
"""
import datetime, re, sys

def parse_time(text):
    m = re.search(r";\s*estimated printing time[^=]*=\s*(.+)", text)
    if not m: return 0.0
    t = 0.0
    for v, u in re.findall(r"(\d+)\s*([dhms])", m.group(1)):
        t += int(v) * {"d": 86400, "h": 3600, "m": 60, "s": 1}[u]
    return t

def cfg(text, key, default=""):
    m = re.search(r"^;\s*" + re.escape(key) + r"\s*=\s*(.+)$", text, re.M)
    return m.group(1).split(",")[0].strip().strip('"') if m else default

def build(text, nozzle="0.3"):
    if text.startswith(";Header Start"): return text      # idempotent
    xs, ys, zs = [], [], []
    z = 0.0
    for line in text.splitlines():
        c = line.split(";", 1)[0]
        if not re.match(r"\s*G[01]\b", c): continue
        for a, arr in (("X", xs), ("Y", ys)):
            m = re.search(a + r"(-?\d+\.?\d*)", c)
            if m: arr.append(float(m.group(1)))
        m = re.search(r"Z(-?\d+\.?\d*)", c)
        if m: z = float(m.group(1)); zs.append(z)
    lines = text.split("\n")
    valid = sum(1 for l in lines if l and not l.startswith(";"))
    nz = cfg(text, "nozzle_diameter", nozzle)
    speed = cfg(text, "sparse_infill_speed", "60")
    try: speed = str(round(float(speed) * 60))
    except ValueError: pass
    h = [";Header Start", "", f";header_type: 3dp,{nz}mm",
         ";file_total_lines: @", f";file_valid_lines: {valid}",
         f";estimated_time(s): {parse_time(text):.0f}",
         f";material_type: {cfg(text, 'filament_type', 'PLA')}",
         f";nozzle_temperature(°C): {cfg(text, 'nozzle_temperature', '210')}",
         f";build_plate_temperature(°C): {cfg(text, 'hot_plate_temp_initial_layer', cfg(text, 'bed_temperature_initial_layer', '60'))}",
         f";work_speed(mm/minute): {speed}",
         f";max_x(mm): {max(xs, default=0)}", f";max_y(mm): {max(ys, default=0)}", f";max_z(mm): {max(zs, default=0)}",
         f";min_x(mm): {min(xs, default=0)}", f";min_y(mm): {min(ys, default=0)}", f";min_z(mm): {min(zs, default=0)}",
         "", ";Header End", "", ";G-code for 3dp engraving",
         ";Generated by IVI 3licer (compatible header added by ivi3d-printer orca/ivi_fdm_header.py)",
         ";" + datetime.datetime.now().strftime("%a %b %d %Y %H:%M:%S"), ""]
    h[3] = f";file_total_lines: {len(h) + len(lines)}"
    return "\n".join(h) + "\n" + text

def main(argv):
    path = argv[-1]
    with open(path, errors="replace") as f: text = f.read()
    with open(path, "w") as f: f.write(build(text))
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv))
